#!/usr/bin/env python3
"""
FRFT Homomorphism MSS Comparison Script

Compares FRFT(α) vs FRFT(γ) ∘ FRFT(β) using Multi-Scale Spectrogram Loss.
Reads WAV files generated by generate_homomorphism_mss_wavfiles.cpp
"""

import torch
import numpy as np
import pandas as pd
from pathlib import Path
from typing import Tuple
import scipy.io.wavfile as wavfile
from tqdm import tqdm
import matplotlib.pyplot as plt
import seaborn as sns

# Import the MSS loss class (assuming MSS.py is in the same directory)
from MSS import MultiscaleSpectrogramLoss


def load_wav_as_tensor(filepath: str) -> torch.Tensor:
    """Load a WAV file and convert to PyTorch tensor."""
    sample_rate, audio = wavfile.read(filepath)

    # Convert to float and normalize
    if audio.dtype == np.int16:
        audio = audio.astype(np.float32) / 32768.0
    elif audio.dtype == np.int32:
        audio = audio.astype(np.float32) / 2147483648.0
    else:
        audio = audio.astype(np.float32)

    # Convert to torch tensor
    tensor = torch.from_numpy(audio).float()

    return tensor, sample_rate


def compute_mss_for_pair(source_path: str, alpha_path: str, composed_path: str,
                         mss_loss: MultiscaleSpectrogramLoss) -> dict:
    """Compute MSS loss between alpha and composed versions."""

    # Load WAV files
    source, sr1 = load_wav_as_tensor(source_path)
    alpha, sr2 = load_wav_as_tensor(alpha_path)
    composed, sr3 = load_wav_as_tensor(composed_path)

    # Verify sample rates match
    assert sr1 == sr2 == sr3, "Sample rates don't match!"

    # Add batch dimension if needed (MSS expects batched input)
    if source.dim() == 1:
        source = source.unsqueeze(0)
    if alpha.dim() == 1:
        alpha = alpha.unsqueeze(0)
    if composed.dim() == 1:
        composed = composed.unsqueeze(0)

    # Compute MSS losses
    with torch.no_grad():
        # Loss between alpha and composed (homomorphic property test)
        loss_homomorphic = mss_loss(alpha, composed).item()

        # Loss between source and alpha (for reference)
        loss_source_alpha = mss_loss(source, alpha).item()

        # Loss between source and composed (for reference)
        loss_source_composed = mss_loss(source, composed).item()

    return {
        'mss_homomorphic': loss_homomorphic,
        'mss_source_alpha': loss_source_alpha,
        'mss_source_composed': loss_source_composed
    }


def main():
    print("\n" + "="*70)
    print("FRFT Homomorphism MSS Analysis")
    print("="*70 + "\n")

    # Configuration
    base_dir = Path("homomorphism_mss_sources")
    metadata_file = base_dir / "metadata.txt"
    output_file = base_dir / "mss_results.txt"

    # Check if base directory exists
    if not base_dir.exists():
        print(f"Error: Directory '{base_dir}' not found!")
        print("Please run generate_homomorphism_mss_wavfiles first.")
        return

    # Check if metadata file exists
    if not metadata_file.exists():
        print(f"Error: Metadata file '{metadata_file}' not found!")
        return

    # Load metadata
    print(f"Loading metadata from {metadata_file}...")
    metadata = pd.read_csv(metadata_file, sep='\t', comment='#')

    # Convert file path columns to string and drop any NaN rows
    metadata['Source_File'] = metadata['Source_File'].astype(str)
    metadata['Alpha_File'] = metadata['Alpha_File'].astype(str)
    metadata['Composed_File'] = metadata['Composed_File'].astype(str)

    # Remove any rows with 'nan' in file paths
    metadata = metadata[metadata['Source_File'] != 'nan']
    metadata = metadata[metadata['Alpha_File'] != 'nan']
    metadata = metadata[metadata['Composed_File'] != 'nan']

    print(f"✓ Loaded {len(metadata)} valid entries\n")

    # Initialize MSS loss
    # Using scales that match common analysis (power of 2 for efficiency)
    mss_loss = MultiscaleSpectrogramLoss(
        scales=[8192, 4096, 2048],
        overlap=0.75,
        verbose=False
    )
    print("✓ Initialized Multi-Scale Spectrogram Loss")
    print(f"  Scales: {mss_loss.scales}")
    print(f"  Overlap: {mss_loss.overlap}\n")

    # Prepare results storage
    results = []

    # Process each entry
    print("Processing WAV files...")
    for idx, row in tqdm(metadata.iterrows(), total=len(metadata), desc="Computing MSS"):
        source_path = base_dir / row['Source_File']
        alpha_path = base_dir / row['Alpha_File']
        composed_path = base_dir / row['Composed_File']

        # Check if files exist
        if not all([source_path.exists(), alpha_path.exists(), composed_path.exists()]):
            print(f"\n⚠ Warning: Missing files for frequency {row['Frequency']}, sample {row['Sample_ID']}")
            continue

        try:
            # Compute MSS losses
            losses = compute_mss_for_pair(
                str(source_path),
                str(alpha_path),
                str(composed_path),
                mss_loss
            )

            # Store results
            results.append({
                'Frequency': row['Frequency'],
                'Sample_ID': row['Sample_ID'],
                'Alpha': row['Alpha'],
                'Beta': row['Beta'],
                'Gamma': row['Gamma'],
                'MSS_Homomorphic': losses['mss_homomorphic'],
                'MSS_Source_Alpha': losses['mss_source_alpha'],
                'MSS_Source_Composed': losses['mss_source_composed']
            })

        except Exception as e:
            print(f"\n✗ Error processing frequency {row['Frequency']}, sample {row['Sample_ID']}: {e}")
            continue

    # Convert results to DataFrame
    results_df = pd.DataFrame(results)

    # Save results
    print(f"\n\nSaving results to {output_file}...")
    with open(output_file, 'w') as f:
        f.write("# FRFT Homomorphism MSS Analysis Results\n")
        f.write("# MSS_Homomorphic: Loss between FRFT(α) and FRFT(γ) ∘ FRFT(β)\n")
        f.write("# MSS_Source_Alpha: Loss between source and FRFT(α)\n")
        f.write("# MSS_Source_Composed: Loss between source and FRFT(γ) ∘ FRFT(β)\n")
        f.write("# Lower MSS_Homomorphic indicates better homomorphic property\n\n")

    results_df.to_csv(output_file, sep='\t', index=False, mode='a')
    print(f"✓ Saved {len(results_df)} results\n")

    # Print statistics
    print("="*70)
    print("Statistics Summary")
    print("="*70)
    print(f"\nHomomorphic Loss (FRFT(α) vs FRFT(γ)∘FRFT(β)):")
    print(f"  Mean:   {results_df['MSS_Homomorphic'].mean():.6f}")
    print(f"  Median: {results_df['MSS_Homomorphic'].median():.6f}")
    print(f"  Std:    {results_df['MSS_Homomorphic'].std():.6f}")
    print(f"  Min:    {results_df['MSS_Homomorphic'].min():.6f}")
    print(f"  Max:    {results_df['MSS_Homomorphic'].max():.6f}")

    print(f"\nBy Frequency:")
    freq_stats = results_df.groupby('Frequency')['MSS_Homomorphic'].agg(['mean', 'std', 'min', 'max'])
    print(freq_stats.to_string())

    # Create visualization
    print("\n\nGenerating visualizations...")
    create_visualizations(results_df, base_dir)

    print("\n" + "="*70)
    print("Analysis Complete!")
    print("="*70)
    print(f"\nResults saved to: {output_file}")
    print(f"Plots saved to: {base_dir}/plots/\n")


def create_visualizations(results_df: pd.DataFrame, base_dir: Path):
    """Create visualization plots for the results."""

    # Create plots directory
    plots_dir = base_dir / "plots"
    plots_dir.mkdir(exist_ok=True)

    # Set style
    sns.set_style("whitegrid")
    plt.rcParams['figure.dpi'] = 300

    # Plot 1: MSS Homomorphic Loss vs Alpha
    fig, ax = plt.subplots(figsize=(12, 6))

    frequencies = sorted(results_df['Frequency'].unique())
    colors = plt.cm.tab10(np.linspace(0, 1, len(frequencies)))

    for idx, freq in enumerate(frequencies):
        freq_data = results_df[results_df['Frequency'] == freq]
        ax.scatter(freq_data['Alpha'], freq_data['MSS_Homomorphic'],
                   alpha=0.5, s=10, color=colors[idx], label=f'{int(freq)} Hz')

    ax.set_xlabel('Alpha (α)', fontsize=14, fontweight='bold')
    ax.set_ylabel('MSS Homomorphic Loss', fontsize=14, fontweight='bold')
    ax.legend(fontsize=10, ncol=3)
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(plots_dir / 'mss_homomorphic_vs_alpha.png', dpi=300, bbox_inches='tight')
    plt.close()
    print("  ✓ Saved: mss_homomorphic_vs_alpha.png")

    # Plot 2: Distribution of MSS Homomorphic Loss by Frequency
    fig, ax = plt.subplots(figsize=(14, 6))

    freq_data = [results_df[results_df['Frequency'] == freq]['MSS_Homomorphic'].values
                 for freq in frequencies]

    bp = ax.boxplot(freq_data, labels=[f'{int(f)} Hz' for f in frequencies],
                    patch_artist=True, showfliers=False)

    for patch, color in zip(bp['boxes'], colors):
        patch.set_facecolor(color)
        patch.set_alpha(0.6)

    ax.set_xlabel('Frequency', fontsize=14, fontweight='bold')
    ax.set_ylabel('MSS Homomorphic Loss', fontsize=14, fontweight='bold')
    ax.tick_params(axis='x', rotation=45)
    ax.grid(True, alpha=0.3, axis='y')
    plt.tight_layout()
    plt.savefig(plots_dir / 'mss_homomorphic_by_frequency.png', dpi=300, bbox_inches='tight')
    plt.close()
    print("  ✓ Saved: mss_homomorphic_by_frequency.png")

    # Plot 3: Heatmap of mean MSS loss by frequency and alpha bins
    fig, ax = plt.subplots(figsize=(14, 8))

    # Create alpha bins
    results_df['Alpha_Bin'] = pd.cut(results_df['Alpha'], bins=20)

    pivot_table = results_df.pivot_table(
        values='MSS_Homomorphic',
        index='Frequency',
        columns='Alpha_Bin',
        aggfunc='mean'
    )

    sns.heatmap(pivot_table, cmap='viridis', ax=ax, cbar_kws={'label': 'Mean MSS Loss'})
    ax.set_xlabel('Alpha Bin', fontsize=14, fontweight='bold')
    ax.set_ylabel('Frequency (Hz)', fontsize=14, fontweight='bold')
    plt.tight_layout()
    plt.savefig(plots_dir / 'mss_heatmap.png', dpi=300, bbox_inches='tight')
    plt.close()
    print("  ✓ Saved: mss_heatmap.png")


if __name__ == "__main__":
    main()