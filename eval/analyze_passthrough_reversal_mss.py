#!/usr/bin/env python3
"""
FRFT Pass-Through and Reversal Test - MSS Analysis

Analyzes the waveforms generated by the C++ test using Multi-Scale Spectrogram Loss.
Computes MSS and MSE between processed and expected outputs.
"""

import torch
import numpy as np
import pandas as pd
from pathlib import Path
from typing import Tuple, Dict, List
import scipy.io.wavfile as wavfile
from tqdm import tqdm
import argparse

# Import the MSS loss class (assumes MSS.py is in same directory)
try:
    from MSS import MultiscaleSpectrogramLoss
except ImportError:
    print("Error: MSS.py not found. Please ensure it's in the same directory.")
    exit(1)


def load_wav_as_tensor(filepath: Path) -> Tuple[torch.Tensor, int]:
    """Load a WAV file and convert to PyTorch tensor."""
    sample_rate, audio = wavfile.read(filepath)

    # Convert to float and normalize
    if audio.dtype == np.int16:
        audio = audio.astype(np.float32) / 32768.0
    elif audio.dtype == np.int32:
        audio = audio.astype(np.float32) / 2147483648.0
    else:
        audio = audio.astype(np.float32)

    # Convert to torch tensor and add batch dimension
    tensor = torch.from_numpy(audio).float().unsqueeze(0)
    return tensor, sample_rate


def analyze_test_results(base_dir: Path, mss_loss: MultiscaleSpectrogramLoss) -> Dict:
    """
    Analyze all waveforms in the test results directory.

    Returns a dictionary with analysis results organized by test type and window size.
    """
    wavs_dir = base_dir / "waveforms"

    if not wavs_dir.exists():
        print(f"Error: Waveforms directory not found: {wavs_dir}")
        return {}

    # Find all waveform files
    wav_files = list(wavs_dir.glob("*.wav"))

    if not wav_files:
        print(f"Error: No waveform files found in {wavs_dir}")
        return {}

    print(f"\nFound {len(wav_files)} waveform files")

    # Organize files by test type, window size, and frame
    organized = {}

    for wav_file in wav_files:
        name = wav_file.stem
        parts = name.split('_')

        # Parse filename: {test_type}_ws{size}_f{frame}_{type}.wav
        # e.g., passthrough_ws128_f1_source.wav
        # or reversal_fwd_ws128_f1_source.wav (multi-part test name)

        # Find the ws{size} part
        ws_idx = None
        for i, part in enumerate(parts):
            if part.startswith('ws') and len(part) > 2:
                try:
                    window_size = int(part[2:])
                    ws_idx = i
                    break
                except ValueError:
                    continue

        if ws_idx is None:
            continue

        # Don't filter by window size - process all window sizes
        # MSS will be computed only for window_size >= 8096 later

        # Test type is everything before ws{size}
        test_type = '_'.join(parts[:ws_idx])

        # Frame number is after ws{size}
        if ws_idx + 1 >= len(parts) or not parts[ws_idx + 1].startswith('f'):
            continue

        try:
            frame_num = int(parts[ws_idx + 1][1:])
        except ValueError:
            continue

        # File type is after frame number
        if ws_idx + 2 >= len(parts):
            continue

        file_type = parts[ws_idx + 2]  # source, processed, expected

        key = (test_type, window_size, frame_num)

        if key not in organized:
            organized[key] = {}

        organized[key][file_type] = wav_file

    # Analyze each test case
    results = []

    print(f"\nAnalyzing waveforms (MSS for window_size >= 8096, MSE for all windows)...")
    print(f"Total organized test cases: {len(organized)}\n")
    for (test_type, window_size, frame_num), files in tqdm(sorted(organized.items())):
        # Check if we have all required files
        if 'processed' not in files or 'expected' not in files:
            print(f"Warning: Missing files for {test_type}_ws{window_size}_f{frame_num}")
            continue

        try:
            # Load waveforms
            processed, sr1 = load_wav_as_tensor(files['processed'])
            expected, sr2 = load_wav_as_tensor(files['expected'])

            if 'source' in files:
                source, sr0 = load_wav_as_tensor(files['source'])
            else:
                source = None

            # Verify sample rates match
            if sr1 != sr2:
                print(f"Warning: Sample rate mismatch for {test_type}_ws{window_size}_f{frame_num}")
                continue

            # Compute losses
            with torch.no_grad():
                # Only compute MSS for window sizes >= 8096 (requires longer signals)
                if window_size >= 8096:
                    mss = mss_loss(processed, expected).item()
                else:
                    mss = None  # Not computed for small windows

                # Always compute MSE for all window sizes
                mse = torch.mean((processed - expected) ** 2).item()

            # Store results
            result = {
                'test_type': test_type,
                'window_size': window_size,
                'frame_num': frame_num,
                'sample_rate': sr1,
                'mss_loss': mss,  # May be None for small windows
                'mse_loss': mse,
                'processed_file': files['processed'].name,
                'expected_file': files['expected'].name
            }

            if source is not None:
                # Also compute loss between source and processed
                with torch.no_grad():
                    if window_size >= 8096:
                        mss_source = mss_loss(source, processed).item()
                    else:
                        mss_source = None

                    mse_source = torch.mean((source - processed) ** 2).item()

                result['mss_source_vs_processed'] = mss_source
                result['mse_source_vs_processed'] = mse_source

            results.append(result)

        except Exception as e:
            print(f"Error processing {test_type}_ws{window_size}_f{frame_num}: {e}")
            continue

    return results


def save_results(results: List[Dict], output_file: Path):
    """Save analysis results to a text file."""
    df = pd.DataFrame(results)

    if df.empty:
        print("No results to save")
        return

    with open(output_file, 'w') as f:
        f.write("FRFT Pass-Through and Reversal Test - MSS Analysis Results\n")
        f.write("=" * 70 + "\n")
        f.write("Note: MSS computed for window sizes >= 8096 samples\n")
        f.write("      MSE computed for all window sizes\n")
        f.write("=" * 70 + "\n\n")

        # Overall statistics
        f.write("Overall Statistics:\n")
        f.write("-" * 70 + "\n")
        f.write(f"Total test cases analyzed: {len(df)}\n")

        # MSS statistics (only for non-None values, i.e., window_size >= 8096)
        mss_df = df[df['mss_loss'].notna()]
        f.write(f"MSS Loss (processed vs expected, window_size >= 8096):\n")
        f.write(f"  Cases:  {len(mss_df)}\n")
        f.write(f"  Mean:   {mss_df['mss_loss'].mean():.6f}\n")
        f.write(f"  Median: {mss_df['mss_loss'].median():.6f}\n")
        f.write(f"  Std:    {mss_df['mss_loss'].std():.6f}\n")
        f.write(f"  Min:    {mss_df['mss_loss'].min():.6f}\n")
        f.write(f"  Max:    {mss_df['mss_loss'].max():.6f}\n\n")

        f.write(f"MSE Loss (processed vs expected, all windows):\n")
        f.write(f"  Cases:  {len(df)}\n")
        f.write(f"  Mean:   {df['mse_loss'].mean():.6e}\n")
        f.write(f"  Median: {df['mse_loss'].median():.6e}\n")
        f.write(f"  Std:    {df['mse_loss'].std():.6e}\n")
        f.write(f"  Min:    {df['mse_loss'].min():.6e}\n")
        f.write(f"  Max:    {df['mse_loss'].max():.6e}\n\n")

        # Statistics by test type
        f.write("\n" + "=" * 70 + "\n")
        f.write("Statistics by Test Type:\n")
        f.write("=" * 70 + "\n\n")

        for test_type in sorted(df['test_type'].unique()):
            test_df = df[df['test_type'] == test_type]
            f.write(f"\n{test_type.upper()}:\n")
            f.write("-" * 70 + "\n")

            # MSS statistics (only for non-None values)
            test_mss_df = test_df[test_df['mss_loss'].notna()]
            f.write(f"MSS Loss (window_size >= 8096):\n")
            f.write(f"  Cases:  {len(test_mss_df)}\n")
            if len(test_mss_df) > 0:
                f.write(f"  Mean:   {test_mss_df['mss_loss'].mean():.6f}\n")
                f.write(f"  Median: {test_mss_df['mss_loss'].median():.6f}\n")
                f.write(f"  Std:    {test_mss_df['mss_loss'].std():.6f}\n")
                f.write(f"  Min:    {test_mss_df['mss_loss'].min():.6f}\n")
                f.write(f"  Max:    {test_mss_df['mss_loss'].max():.6f}\n")
            else:
                f.write(f"  (No MSS data for this test type)\n")
            f.write("\n")

            f.write(f"MSE Loss (all windows):\n")
            f.write(f"  Cases:  {len(test_df)}\n")
            f.write(f"  Mean:   {test_df['mse_loss'].mean():.6e}\n")
            f.write(f"  Median: {test_df['mse_loss'].median():.6e}\n")
            f.write(f"  Std:    {test_df['mse_loss'].std():.6e}\n")
            f.write(f"  Min:    {test_df['mse_loss'].min():.6e}\n")
            f.write(f"  Max:    {test_df['mse_loss'].max():.6e}\n\n")

            # By window size within test type
            f.write(f"  By Window Size:\n")
            for ws in sorted(test_df['window_size'].unique()):
                ws_df = test_df[test_df['window_size'] == ws]
                mss_val = ws_df['mss_loss'].mean()
                mse_val = ws_df['mse_loss'].mean()

                if pd.notna(mss_val):
                    f.write(f"    {ws:6d}: MSS={mss_val:.6f}, MSE={mse_val:.6e}\n")
                else:
                    f.write(f"    {ws:6d}: MSS=N/A, MSE={mse_val:.6e}\n")

        # Detailed results table
        f.write("\n\n" + "=" * 70 + "\n")
        f.write("Detailed Results:\n")
        f.write("=" * 70 + "\n\n")

    # Append detailed table
    df_sorted = df.sort_values(['test_type', 'window_size', 'frame_num'])
    df_sorted.to_csv(output_file, sep='\t', index=False, mode='a')

    print(f"\n✓ Results saved to: {output_file}")


def main():
    parser = argparse.ArgumentParser(
        description='Analyze FRFT pass-through and reversal test results using MSS loss'
    )
    parser.add_argument(
        '--dir',
        type=str,
        default='test_results/passthrough_reversal',
        help='Base directory containing test results (default: test_results/passthrough_reversal)'
    )
    args = parser.parse_args()

    print("\n" + "=" * 70)
    print("FRFT Pass-Through and Reversal Test - MSS Analysis")
    print("=" * 70)

    base_dir = Path(args.dir)

    if not base_dir.exists():
        print(f"\nError: Directory not found: {base_dir}")
        print("Please run the C++ test first to generate waveforms.")
        return

    print(f"\nBase directory: {base_dir}")

    # Initialize MSS loss
    print("\nInitializing Multi-Scale Spectrogram Loss...")
    mss_loss = MultiscaleSpectrogramLoss()

    # Analyze results
    results = analyze_test_results(base_dir, mss_loss)

    if not results:
        print("\nNo results to analyze. Check that waveforms were generated correctly.")
        return

    # Save results
    output_file = base_dir / "mss_analysis_results.txt"
    save_results(results, output_file)

    print("\n" + "=" * 70)
    print("Analysis Complete!")
    print("=" * 70)
    print(f"\nResults: {output_file}")
    print(f"Total test cases analyzed: {len(results)}")
    print()


if __name__ == "__main__":
    main()